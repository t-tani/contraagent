// Generate src/schema.ts (types only: tsc emits its .d.ts into dist) from the monitor's committed OpenAPI document.
// `--check` fails instead of writing when the committed file is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = new URL('../../../../src/contraagent/_internal/monitor/openapi.json', import.meta.url);
const OUT = new URL('../src/schema.ts', import.meta.url);
const HEADER = '// Generated by `pnpm gen` from src/contraagent/_internal/monitor/openapi.json. Do not edit.\n\n';

const ast = await openapiTS(JSON.parse(await readFile(SPEC, 'utf8')), {
  exportType: true,
  // The server omits unset fields (exclude_unset): a field with a default may be absent.
  defaultNonNullable: false,
});
const next = HEADER + astToString(ast);
if (process.argv.includes('--check')) {
  const cur = await readFile(OUT, 'utf8').catch(() => '');
  if (cur !== next) {
    console.error(`${fileURLToPath(OUT)} is stale: run \`pnpm gen\``);
    process.exit(1);
  }
} else {
  await writeFile(OUT, next);
}
