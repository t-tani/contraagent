"""Write the public API, as griffe reads it from the sources, to `tests/api/contraagent.api.txt`.

    uv run python tests/api/snapshot.py

Every name in the `__all__` of a public module, with its kind and its full signature: a
class's bases, decorators, fields (annotation and default) and public methods; a
function's parameters and return type; a constant's or alias's annotation and value.
Members are sorted by name (`__init__` and `__call__` first), so a diff shows what
changed and nothing else. Docstrings are left out. `tests/test_public_api.py` fails
while the committed file differs from what this writes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import griffe

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = Path(__file__).with_name("contraagent.api.txt")
COMMAND = "uv run python tests/api/snapshot.py"
PUBLIC = (
    "contraagent",
    "contraagent.config",
    "contraagent.backends",
    "contraagent.engine",
    "contraagent.plugins",
    "contraagent.monitor",
    "contraagent.monitor.api",
    "contraagent.testing",
)
WIDTH = 110
SPECIAL = ("__init__", "__call__")


def render() -> str:
    package = griffe.load("contraagent", search_paths=[str(ROOT / "src")], resolve_aliases=True, resolve_external=False)
    assert isinstance(package, griffe.Module)
    public = {f"{module}.{name}" for module in PUBLIC for name in _exports(package, module)}
    exported = {_target(package, path).path for path in public}
    lines = [f"# The public API of contraagent. Generated by `{COMMAND}`; do not edit.", ""]
    for module in PUBLIC:
        lines += [f"## {module}", ""]
        for name in sorted(_exports(package, module)):
            obj = _target(package, f"{module}.{name}")
            lines += _object(name, obj, exported)
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _exports(package: griffe.Module, module: str) -> list[str]:
    mod = package if module == "contraagent" else package[module.removeprefix("contraagent.")]
    return [str(name) for name in mod.exports or ()]


def _target(package: griffe.Module, path: str) -> griffe.Object:
    obj = package[path.removeprefix("contraagent.")]
    return obj.final_target if isinstance(obj, griffe.Alias) else obj


def _object(name: str, obj: griffe.Object, exported: set[str]) -> list[str]:
    if isinstance(obj, griffe.Class):
        return _class(name, obj, exported)
    if isinstance(obj, griffe.Function):
        return _function(name, obj, "")
    if isinstance(obj, griffe.Attribute):
        return [_attribute(name, obj, "")]
    if isinstance(obj, griffe.TypeAlias):
        return [f"type {name} = {obj.value}"]
    return [f"{obj.kind.value} {name}"]


def _class(name: str, cls: griffe.Class, exported: set[str]) -> list[str]:
    lines = [f"@{d.value}" for d in cls.decorators]
    params = f"[{', '.join(_type_parameter(p) for p in cls.type_parameters)}]" if cls.type_parameters else ""
    bases = f"({', '.join(str(b) for b in cls.bases)})" if cls.bases else ""
    lines.append(f"class {name}{params}{bases}")
    members: dict[str, griffe.Object | griffe.Alias] = {}
    # Members a non-public contraagent base defines belong to this class's API.
    for base in reversed(_internal_bases(cls, exported)):
        members.update(base.members)
    members.update(cls.members)
    for key in sorted(members, key=lambda n: (n not in SPECIAL, SPECIAL.index(n) if n in SPECIAL else 0, n)):
        if key.startswith("_") and key not in SPECIAL:
            continue
        member = members[key]
        if isinstance(member, griffe.Alias):
            try:
                member = member.final_target
            except griffe.AliasResolutionError:
                continue
        if isinstance(member, griffe.Function):
            lines += _function(key, member, "    ")
        elif isinstance(member, griffe.Attribute):
            lines.append(_attribute(key, member, "    "))
        elif isinstance(member, griffe.Class):
            lines += ["    " + line for line in _class(key, member, exported)]
    return lines


def _type_parameter(p: griffe.TypeParameter) -> str:
    star = {griffe.TypeParameterKind.type_var_tuple: "*", griffe.TypeParameterKind.param_spec: "**"}.get(p.kind, "")
    bound = f": {p.bound}" if p.bound is not None else ""
    default = f" = {p.default}" if p.default is not None else ""
    return f"{star}{p.name}{bound}{default}"


def _internal_bases(cls: griffe.Class, exported: set[str]) -> list[griffe.Class]:
    out = []
    for base in cls.resolved_bases:
        if base.path.startswith("contraagent.") and base.path not in exported and isinstance(base, griffe.Class):
            out += [base, *_internal_bases(base, exported)]
    return out


def _function(name: str, fn: griffe.Function, indent: str) -> list[str]:
    lines = []
    for overload in fn.overloads or ():
        lines += [f"{indent}@overload", *_function(name, overload, indent)]
    labels = fn.labels
    lines += [f"{indent}@{label}" for label in ("classmethod", "staticmethod", "property", "abstractmethod") if label in labels]
    prefix = f"{indent}{'async ' if 'async' in labels else ''}def {name}("
    suffix = f") -> {fn.returns}" if fn.returns is not None else ")"
    params = _parameters(fn)
    one = prefix + ", ".join(params) + suffix
    if len(one) <= WIDTH or not params:
        return [*lines, one]
    return [*lines, prefix, *(f"{indent}    {p}," for p in params), indent + suffix]


def _parameters(fn: griffe.Function) -> list[str]:
    out: list[str] = []
    kinds = griffe.ParameterKind
    previous = None
    for p in fn.parameters:
        if previous is kinds.positional_only and p.kind is not kinds.positional_only:
            out.append("/")
        if p.kind is kinds.keyword_only and previous not in (kinds.keyword_only, kinds.var_positional):
            out.append("*")
        star = {kinds.var_positional: "*", kinds.var_keyword: "**"}.get(p.kind, "")
        text = f"{star}{p.name}"
        if p.annotation is not None:
            text += f": {p.annotation}"
        if p.default is not None and not star:
            text += f" = {p.default}" if p.annotation is not None else f"={p.default}"
        out.append(text)
        previous = p.kind
    if previous is kinds.positional_only:
        out.append("/")
    return out


def _attribute(name: str, attr: griffe.Attribute, indent: str) -> str:
    text = f"{indent}{name}"
    if "property" in attr.labels:
        text = f"{indent}@property {name}"
    if attr.annotation is not None:
        text += f": {attr.annotation}"
    # A value assigned in a method (`self.x = ...`) is code, not a default.
    if attr.value is not None and attr.labels & {"class-attribute", "module-attribute"}:
        text += f" = {' '.join(str(attr.value).split())}"
    return text


def main() -> None:
    SNAPSHOT.write_text(render())
    sys.stdout.write(f"wrote {SNAPSHOT.relative_to(ROOT)}\n")


if __name__ == "__main__":
    main()
